import { SectionUnavailable } from "@/components/DataOutage";
import { uiMessage } from "@/lib/error-copy";
import { queryOptions, useQuery, useQueryClient } from "@tanstack/react-query";
import { useServerFn } from "@tanstack/react-start";
import { RefreshCw } from "lucide-react";
import { useState } from "react";
import { toast } from "sonner";

import { Button } from "@/components/ui/button";
import { generateBrief, getBrief } from "@/lib/analyst.functions";

export const briefQuery = () =>
  queryOptions({ queryKey: ["analyst-brief"], queryFn: () => getBrief() });

/** The brief's first sentence, for use as a closed-disclosure teaser. */
export function useBriefTeaser(): string | null {
  const { data } = useQuery(briefQuery());
  if (!data?.brief) return null;
  const first = data.brief
    .replace(/\s+/g, " ")
    .trim()
    .split(/(?<=\.)\s/)[0];
  return first ?? null;
}

function dateLabel(iso: string) {
  return new Date(`${iso}T12:00:00Z`).toLocaleDateString("en-GB", {
    weekday: "long",
    day: "numeric",
    month: "long",
    timeZone: "Asia/Kolkata",
  });
}

/**
 * Renders the stored brief only. The words are generated once by cron; this
 * component never asks a model for anything, so the text cannot drift between
 * two readers on the same morning.
 */
export function AnalystBrief({ bare = false }: { bare?: boolean }) {
  const { data, isError, error } = useQuery(briefQuery());
  const regenerate = useServerFn(generateBrief);
  const qc = useQueryClient();
  const [busy, setBusy] = useState(false);

  if (isError)
    return (
      <SectionUnavailable
        title="Morning brief"
        detail={error instanceof Error ? error.message : null}
      />
    );
  if (!data || !data.configured) return null;

  async function onRegenerate() {
    setBusy(true);
    const id = toast.loading("Writing the brief…");
    try {
      const r = await regenerate();
      if (r.status === "success") {
        toast.success(`Brief written for ${r.for_date}.`, { id });
        await qc.invalidateQueries();
      } else {
        toast.error(r.error ?? "Brief generation failed.", { id });
      }
    } catch (e) {
      toast.error(uiMessage(e, "the morning brief"), { id });
    } finally {
      setBusy(false);
    }
  }

  const failed = data.failure !== null && data.brief === null;

  const header = (
    <div
      className={
        bare
          ? "flex items-center gap-3 pb-2"
          : "border-border flex items-center gap-3 border-b px-4 py-2"
      }
    >
      {bare ? null : (
        <h2 className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">
          Morning brief
        </h2>
      )}
      {data.for_date ? (
        <span className="text-[11px] text-muted-foreground">for {dateLabel(data.for_date)}</span>
      ) : null}
      <Button
        size="sm"
        variant="ghost"
        disabled={busy}
        onClick={() => void onRegenerate()}
        className="ml-auto h-6 gap-1.5 text-[11px]"
      >
        <RefreshCw className={`size-3 ${busy ? "animate-spin" : ""}`} />
        Rewrite
      </Button>
    </div>
  );

  const body =
    failed || !data.brief ? (
      <div className={bare ? "text-[13px]" : "px-4 py-4 text-[13px]"}>
        {/* Three different states, never conflated: the generator failed, the
            brief simply has not been written yet, or we could not read it. */}
        <p className="font-medium">
          {failed
            ? "No brief today — the writer could not finish"
            : "No brief has been written for this day yet"}
        </p>
        <p className="mt-1 text-xs text-muted-foreground">
          {failed
            ? "The technical detail is on the Feed Health screen."
            : "Nothing has failed — the morning writer has not run for this date. Use Rewrite to write one now."}
        </p>
      </div>
    ) : (
      <div className={bare ? "" : "px-4 py-4"}>
        {data.superseded ? (
          <p className="border-warning/40 bg-warning/10 text-warning-foreground mb-3 rounded-md border px-3 py-2 text-[12px]">
            A counting rule changed after this brief was written, so some figures below were worked
            out the old way. What changed: {data.superseded.what} Use Rewrite for a brief on the
            current rules.
          </p>
        ) : null}
        {data.brief.split(/\n{2,}/).map((para, i) => (
          <p key={i} className="mt-2 max-w-3xl text-[13px] leading-relaxed first:mt-0">
            {para}
          </p>
        ))}
        <p className="mt-3 text-[11px] text-muted-foreground">
          Written from stored figures only — every number in this brief is checked against the
          evidence set before it is saved. No figure here is generated by the model.
        </p>
      </div>
    );


  if (bare) {
    return (
      <div>
        {header}
        {body}
      </div>
    );
  }

  return (
    <section className="border-border bg-card mt-4 rounded-md border">
      {header}
      {body}
    </section>
  );
}
